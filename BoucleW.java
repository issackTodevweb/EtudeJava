    // La boucle while
// La boucle while signifie « tant que ».
// Elle répète des instructions tant qu'une condition est vraie. Elle est pratique lorsque tu ne connais pas à l'avance le nombre de répétitions.






public class BoucleW {
    public static void main(String[] args) {
        int i = 1;                                // int i = 1; : crée un compteur qui commence à 1.
        while (i <= 5){                           // while (i <= 5) : répète le bloc tant que i est inférieur ou égal à 5.
            System.out.println(i);
            i++;                                  // i++; : augmente le compteur pour avancer vers la fin.
        }
    }
}
